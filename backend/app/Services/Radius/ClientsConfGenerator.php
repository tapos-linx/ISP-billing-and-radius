<?php

declare(strict_types=1);

namespace App\Services\Radius;

use Illuminate\Support\Facades\Crypt;
use Illuminate\Support\Facades\DB;
use InvalidArgumentException;
use Throwable;

class ClientsConfGenerator
{
    /**
     * Render FreeRADIUS clients.conf strictly enforcing /32 point-to-point WireGuard IPs
     * and fail-closed security preventing 0.0.0.0 or 0.0.0.0/0 open relays.
     */
    public function render(): string
    {
        $lines = [];
        $lines[] = '# ====================================================================';
        $lines[] = '# FreeRADIUS 3.2 Hardened clients.conf - Auto-Generated by Carrier BSS';
        $lines[] = '# Invariant: Zero open relays. require_message_authenticator = yes';
        $lines[] = '# ====================================================================';
        $lines[] = '';

        // 1. Process NAS table entries
        $nasRecords = DB::table('nas')->orderBy('id')->get();
        foreach ($nasRecords as $nas) {
            $ip = trim((string) $nas->nasname);
            $this->validateIpAddress($ip);

            $shortname = ! empty($nas->shortname) ? (string) $nas->shortname : 'nas_'.$nas->id;
            $secret = ! empty($nas->secret) ? (string) $nas->secret : 'insecure_default_secret';
            $type = ! empty($nas->type) ? (string) $nas->type : 'other';

            $lines[] = "client {$shortname} {";
            $lines[] = "    ipaddr = {$ip}";
            $lines[] = "    secret = {$secret}";
            $lines[] = '    require_message_authenticator = yes';
            $lines[] = "    nas_type = {$type}";
            $lines[] = '}';
            $lines[] = '';
        }

        // 2. Process WireGuard VPN peers
        $wgPeers = DB::table('wireguard_peers')->where('status', 'active')->orderBy('id')->get();
        foreach ($wgPeers as $peer) {
            $ip = trim((string) $peer->wireguard_ip);
            $this->validateIpAddress($ip);

            $secret = '';
            try {
                $secret = Crypt::decryptString((string) $peer->radius_secret_encrypted);
            } catch (Throwable) {
                $secret = (string) $peer->radius_secret_encrypted;
            }

            $shortname = (string) $peer->shortname;

            $lines[] = "client {$shortname} {";
            $lines[] = "    ipaddr = {$ip}";
            $lines[] = "    secret = {$secret}";
            $lines[] = '    require_message_authenticator = yes';
            $lines[] = '    nas_type = other';
            $lines[] = '}';
            $lines[] = '';
        }

        return implode("\n", $lines);
    }

    /**
     * Strict security validation: Reject 0.0.0.0, 0.0.0.0/0, wildcard or invalid addresses.
     */
    public function validateIpAddress(string $ip): void
    {
        $cleanIp = explode('/', $ip)[0];

        if ($cleanIp === '0.0.0.0' || $ip === '0.0.0.0/0' || $cleanIp === '*' || empty($cleanIp)) {
            throw new InvalidArgumentException(
                "CRITICAL SECURITY VIOLATION: Wildcard 0.0.0.0 or 0.0.0.0/0 is strictly forbidden in clients.conf (detected: '{$ip}')"
            );
        }

        if (! filter_var($cleanIp, FILTER_VALIDATE_IP)) {
            throw new InvalidArgumentException("Invalid IP address format for RADIUS client: '{$ip}'");
        }
    }
}
